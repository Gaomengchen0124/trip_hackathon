import test from 'node:test'
import assert from 'node:assert/strict'
import {chromium} from 'playwright'
const base=process.env.FORMAL_TEST_BASE_URL||'http://127.0.0.1:5192'
test('merged Vue: recommendation → selection → AI optimization → additions → revision → undo → reload → tickets',{timeout:60000},async t=>{
 const browser=await chromium.launch({headless:true,channel:'chrome'});t.after(()=>browser.close())
 const page=await browser.newPage({viewport:{width:1280,height:900}})
 page.setDefaultTimeout(10000)
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto(base+'/recommend')
 await page.locator('#recommend-city').selectOption('上海')
 await page.getByRole('button',{name:'为我寻找灵感',exact:true}).click()
 await page.locator('.results a[href*="fanhua-shanghai"]').click()
 await page.waitForURL(/\/line\/fanhua-shanghai/)
 await page.getByRole('link',{name:'← 返回推荐筛选',exact:true}).waitFor()
 await page.locator('a[href="/customize/fanhua-shanghai"]').first().click()
 await page.locator('.poi-option').first().waitFor()
 await page.locator('.poi-option').nth(0).click()
 await page.locator('.poi-option').nth(1).click()
 await page.locator('.poi-option').nth(2).click()
 await page.getByLabel('开始日期',{exact:true}).fill('2026-11-10')
 await page.getByLabel('结束日期',{exact:true}).fill('2026-11-11')
 await page.locator('#planning-panel [data-planning-action="generate"]').click()
 await page.waitForURL(/\/itinerary\//)
 t.diagnostic('await page.waitForURL(/\\/itinerary\\//)')
 await page.getByText('本行程由大模型与圣地巡礼算法合作优化生成；时间仅供参考，开放与预约以官方信息为准。',{exact:true}).waitFor()
 const original=await page.locator('.planning-result .stop.visit').count()
 assert.equal(original,3)
 await page.locator('.revision-recommendations .revision-candidate input').first().check()
 await page.getByRole('button',{name:'查看追加预览',exact:true}).click()
 await page.getByRole('button',{name:'应用新行程',exact:true}).click()
 await page.waitForFunction(n=>document.querySelectorAll('.planning-result .stop.visit').length===n,original+1)
 await page.getByRole('button',{name:'撤销上次修改',exact:true}).click()
 await page.waitForFunction(n=>document.querySelectorAll('.planning-result .stop.visit').length===n,original)
 await page.locator('.revision-composer textarea').fill('最后一个景点不去了')
 await page.getByRole('button',{name:'发送行程调整',exact:true}).click()
 await page.getByRole('button',{name:'应用新行程',exact:true}).waitFor()
 t.diagnostic("await page.getByRole('button',{name:'应用新行程',exact:true}).waitFor()")
 assert.equal(await page.locator('.planning-result .stop.visit').count(),original)
 await page.getByRole('button',{name:'保留原行程',exact:true}).click()
 assert.equal(await page.locator('.planning-result .stop.visit').count(),original)
 await page.getByRole('button',{name:'发送行程调整',exact:true}).click()
 await page.getByRole('button',{name:'应用新行程',exact:true}).click()
 await page.waitForFunction(n=>document.querySelectorAll('.planning-result .stop.visit').length===n,original-1)
 await page.getByRole('button',{name:'撤销上次修改',exact:true}).click()
 await page.waitForFunction(n=>document.querySelectorAll('.planning-result .stop.visit').length===n,original)
 await page.reload();await page.locator('#revision-workspace').waitFor()
 t.diagnostic("await page.reload();await page.locator('#revision-workspace').waitFor()")
 assert.equal(await page.locator('.planning-result .stop.visit').count(),original)
 await page.locator('.itinerary-ticket-action:not([disabled])').first().click()
 await page.getByText('合成测试成人票',{exact:true}).waitFor()
 await page.getByRole('button',{name:'关闭门票浮窗',exact:true}).click()
 await page.getByRole('button',{name:'刷新推荐',exact:true}).click()
 await page.locator('.revision-recommendations').waitFor()
 await page.setViewportSize({width:390,height:844})
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
 assert.deepEqual(errors,[])
 const other=await browser.newContext();t.after(()=>other.close())
 const response=await other.request.get(page.url().replace('/itinerary/','/api/itineraries/'))
 assert.equal(response.status(),404)
})
