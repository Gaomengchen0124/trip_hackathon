async function setup(options = {}, signedIn = false) {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, ...options })
  await context.route(base + '/api/**', route => {
    const path = new URL(route.request().url()).pathname
    const data = path === '/api/auth/session' ? { user: signedIn ? { id: 'journal-test', nickname: '巡礼旅人', role: 'user', provider: 'email' } : null }
      : path === '/api/me/interests' ? { profile: null }
      : path.includes('/catalog') ? { works: [], cities: ['上海'] } : []
    return route.fulfill({ json: data })
  })
  const page = await context.newPage()
  page.setDefaultTimeout(10000)
  page.on('pageerror', error => errors.push(error.message))
  return { context, page }
}
async function opened(page, query = '') {
  await page.goto(base + '/' + query)
  await page.locator('.opening-chapter').waitFor()
  await page.locator('.intro-wordmark img').evaluateAll(images => Promise.all(images.map(img => img.decode().catch(() => {}))))
  await page.waitForTimeout(120)
}
async function range(page) { return page.evaluate(() => document.querySelector('.opening-chapter').offsetHeight - document.querySelector('.opening-sequence').offsetHeight) }
async function arrived(page) {
  // History updates the URL before Vue and its view transition settle.
  await page.waitForFunction(() => document.querySelector('.opening-chapter[inert]') && !document.querySelector('.story-content[inert]') && !document.documentElement.classList.contains('is-opening-story') && !document.documentElement.dataset.atlasTurn)
  assert.equal(await page.locator('.opening-chapter').count(), 1, 'The opening remains part of the home document')
  assert.equal(await page.locator('.opening-chapter[inert]').count(), 1, 'Offscreen opening controls leave the keyboard focus order')
  assert.equal(await page.locator('.story-content[inert]').count(), 0)
  assert.equal(await page.evaluate(() => document.documentElement.classList.contains('is-opening-story')), false)
}
